"""m6502gen.py OM6502.LST DM6502.LST OUT.H -- MAME's NMOS 6502 as C.

MAME 0.288 describes the 6502 (src/devices/cpu/m6502/om6502.lst, by Olivier
Galibert, BSD-3-Clause) as C-like code per instruction, one bus access a
line, and builds its core from that with m6502make.py. This does what
m6502make.py does for its "partial" functions: the CPU can stop after any
access when the cycles run out, and carry on from there in the next
timeslice, so it stops and starts on exactly the cycles MAME's does.

Where MAME (and Q*bert's generator, ../../qbert/tools/m6502gen.py, which
this began as) makes each instruction a function with a switch to carry on
from, this makes one body for m6502.c's m65_run(): each instruction a
label in it, the registers its locals, a goto to the next instruction (or
to the place to carry on from, kept as a label's address). The 6502's
state stays in the M33's registers from one instruction to the next, and
goes back to its struct only to call the board (an I/O access) or at the
end of the timeslice. MAME's run loop sets m_PPC and m_inst_state at each
instruction for its debugger and its reset: here the reset is m65_run's
to start, and m_PPC isn't kept (nothing reads it). An instruction never
ends with no cycles left (its last access would have stopped it), so the
next one starts without a look at the count.

MAME's standard_irq_callback() becomes m65_irq_ack(), which drops a
HOLD_LINE interrupt as MAME's default_irq_callback() does. An access
whose address is in page 0 by its form (a zero page mode's, or an
indirect mode's pointer) is read_zp() / write_zp(), which go to page 0's
RAM without the page map's look.
"""
import re, sys

def load(fname):
    ops = []
    for line in open(fname):
        if line.startswith('#'): continue
        line = line.rstrip()
        if not line: continue
        if line[0] in ' \t':
            if line == '\tprefetch();':
                ops[-1][1] += ['\tprefetch_start();', '\tm_IR = read_sync(m_PC);', '\tprefetch_end();']
            elif line == '\tprefetch_noirq();':
                ops[-1][1] += ['\tprefetch_start();', '\tm_IR = read_sync(m_PC);', '\tprefetch_end_noirq();']
            else:
                ops[-1][1].append(line)
        else:
            ops.append([line.strip(), []])
    return dict(ops)

ops = load(sys.argv[1])
disp = []
for line in open(sys.argv[2]):
    if line.startswith('#'): continue
    disp += line.split()
assert len(disp) == 257, len(disp)       # 256 opcodes and reset

ZP_MODES = ('zpg', 'zpx', 'zpy')

def zero_page(line, mode):
    """page 0's accesses as read_zp / write_zp: an 8-bit address by its form
    (m_TMP2 is 8 bits; a zero page mode's m_TMP is set only from an operand
    byte or an (uint8_t) sum, checked below)"""
    line = re.sub(r'\bread\((m_TMP2|\(m_TMP2\+1\) & 0xff|m_TMP2 & 0xff|\(uint8_t\)\([^()]*\))\)', r'read_zp(\1)', line)
    line = re.sub(r'\bwrite\(((?:\(uint8_t\)\([^()]*\)))\s*,', r'write_zp(\1,', line)
    if mode in ZP_MODES:
        line = re.sub(r'\bread\(m_TMP\)', 'read_zp(m_TMP)', line)
        line = re.sub(r'\bwrite\(m_TMP,', 'write_zp(m_TMP,', line)
    return line

def conv(line):
    line = line.replace('standard_irq_callback(NMI_LINE, m_PC);', 'm65_nmi_ack();')
    line = line.replace('standard_irq_callback(IRQ_LINE, m_PC);', 'm65_irq_ack();')
    assert 'standard_irq_callback' not in line, line
    line = re.sub(r'\b(u?int(?:8|16|32)_t)\(', r'(\1)(', line)
    return line

out = ['// Generated by tools/m6502gen.py from MAME 0.288\'s om6502.lst and dm6502.lst',
       '// (Olivier Galibert, BSD-3-Clause): do not edit. The body of m6502.c\'s m65_run().', '']
names = list(dict.fromkeys(disp))
out.append('static M65_DATA const void *m65_op_tab[257] = {     // (M65_DATA: in RAM on the cart, as m65_run)')
for i in range(0, 257, 4):
    out.append('\t' + ' '.join('&&op_%s,' % n for n in disp[i:i+4]))
out.append('};')
out.append('')
out.append('m65_next:')
out.append('#ifdef M65_TRACE')
out.append('\tif (__builtin_expect(m65_traced, 0)) m65_trace_now();')
out.append('#endif')
out.append('\tgoto *m65_op_tab[m_IR];')
out.append('')
stubs = []
def cycle(name, sub):
    """a bus access done: on with the next, or (the cycles run out) to its
    stub at the body's end, which keeps the place to carry on from"""
    lab = 'op_%s_%d' % (name, sub)
    out.append('\tif (__builtin_expect(--m65_icount <= 0, 0)) goto %s_stop;' % lab)
    out.append('%s:;' % lab)
    stubs.append('%s_stop: M65_STOP(%s);' % (lab, lab))

for name in names:
    out.append('op_%s:' % name)
    sub = 1
    mode = name.split('_')[-1]
    if mode in ZP_MODES:
        for ins in ops[name]:
            for a in re.findall(r'\bm_TMP = ([^;]*);', ins):
                assert a == 'read_pc()' or a.startswith('UINT8(') or a.startswith('uint8_t('), (name, a)
    for ins in ops[name]:
        ins = zero_page(conv(ins), mode)
        if 'eat-all-cycles' in ins:
            out.append('\tm65_icount = 0; M65_STOP(op_%s_%d);' % (name, sub))
            out.append('op_%s_%d:;' % (name, sub))
            sub += 1
        elif 'read' in ins or 'write' in ins:
            out.append(ins)
            cycle(name, sub)
            sub += 1
        else:
            out.append(conv(ins))
    out.append('\tgoto m65_next;')
    out.append('')
out.append('// the stops, out of the way')
out += stubs
open(sys.argv[3], 'w').write('\n'.join(out) + '\n')
